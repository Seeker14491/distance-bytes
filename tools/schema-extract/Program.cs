// Extracts serialization metadata from Distance's Assembly-CSharp.dll:
//
// - schema/components.json: every serializable component class with its component ID, version,
//   whether it has a hand-written Visit method, and its public instance fields (used by the
//   game's reflection-based serialization).
// - crates/distance-bytes/src/generated/component_ids.rs: the ComponentID enum as Rust constants.
//
// Usage: dotnet run -- <path to Assembly-CSharp.dll> <repository root>

using System.Text;
using System.Text.Json;
using Mono.Cecil;
using Mono.Cecil.Cil;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: schema-extract <Assembly-CSharp.dll> <repo root>");
    return 1;
}

var assemblyPath = args[0];
var repoRoot = args[1];

var resolver = new DefaultAssemblyResolver();
resolver.AddSearchDirectory(Path.GetDirectoryName(Path.GetFullPath(assemblyPath)));
var module = ModuleDefinition.ReadModule(assemblyPath, new ReaderParameters { AssemblyResolver = resolver });

// ComponentID enum
var componentIdType = module.GetType("ComponentID") ?? throw new Exception("ComponentID enum not found");
var componentIds = componentIdType.Fields
    .Where(f => f.IsLiteral)
    .Select(f => (Name: f.Name, Value: Convert.ToInt32(f.Constant)))
    .ToList();
var idNames = componentIds.ToDictionary(c => c.Value, c => c.Name);

// Serializable component classes
var components = new List<object>();
foreach (var type in module.GetTypes().Where(t => t.IsClass && !t.IsAbstract).OrderBy(t => t.FullName))
{
    var idGetter = FindGetter(type, "get_ID_");
    if (idGetter == null || idGetter.ReturnType.FullName != "ComponentID")
        continue;

    var id = EvalConstInt(idGetter);
    var versionGetter = FindGetter(type, "get_Version_");
    var version = versionGetter != null ? EvalConstInt(versionGetter) : null;

    components.Add(new
    {
        @class = type.FullName,
        base_classes = BaseChain(type),
        id,
        id_name = id is int i && idNames.TryGetValue(i, out var n) ? n : null,
        version,
        is_serial_component = BaseChain(type).Contains("SerialComponent"),
        visit_override_in = FindVisitDeclaringType(type),
        fields = PublicInstanceFields(type).Select(f => new
        {
            name = f.Name,
            serial_name = ProperSerialName(f.Name),
            type = f.FieldType.FullName,
            declared_in = f.DeclaringType.FullName,
        }),
    });
}

var json = JsonSerializer.Serialize(
    new { component_ids = componentIds.Select(c => new { name = c.Name, value = c.Value }), components },
    new JsonSerializerOptions { WriteIndented = true });
Directory.CreateDirectory(Path.Combine(repoRoot, "schema"));
File.WriteAllText(Path.Combine(repoRoot, "schema", "components.json"), json + "\n");

var rs = new StringBuilder();
rs.AppendLine("// @generated by tools/schema-extract from the game's ComponentID enum. Do not edit.");
rs.AppendLine();
rs.AppendLine("use crate::component_id::ComponentId;");
rs.AppendLine();
rs.AppendLine("#[allow(missing_docs)]");
rs.AppendLine("impl ComponentId {");
foreach (var (name, value) in componentIds)
    rs.AppendLine($"    pub const {ScreamingSnake(name)}: Self = Self({value});");
rs.AppendLine("}");
rs.AppendLine();
rs.AppendLine("/// `(value, name)` pairs sorted by value.");
rs.AppendLine("pub(crate) static NAMES: &[(i32, &str)] = &[");
foreach (var (name, value) in componentIds.OrderBy(c => c.Value))
    rs.AppendLine($"    ({value}, \"{name}\"),");
rs.AppendLine("];");
var rsPath = Path.Combine(repoRoot, "crates", "distance-bytes", "src", "generated", "component_ids.rs");
Directory.CreateDirectory(Path.GetDirectoryName(rsPath)!);
File.WriteAllText(rsPath, rs.ToString().ReplaceLineEndings("\n"));

Console.WriteLine($"{componentIds.Count} component IDs, {components.Count} component classes");
return 0;

static MethodDefinition? FindGetter(TypeDefinition type, string name)
{
    for (var t = type; t != null; t = t.BaseType?.Resolve())
    {
        var m = t.Methods.FirstOrDefault(m => m.Name == name && !m.HasParameters && m.HasBody);
        if (m != null)
            return m;
    }
    return null;
}

// Evaluates methods of the form `return <const>;` or `return OtherStaticMethod();`.
static int? EvalConstInt(MethodDefinition method, int depth = 0)
{
    if (depth > 4 || !method.HasBody)
        return null;
    var ins = method.Body.Instructions.Where(i => i.OpCode != OpCodes.Nop).ToList();
    if (ins.Count < 2 || ins[^1].OpCode != OpCodes.Ret)
        return null;
    var first = ins[0];
    if (ins.Count == 2 && TryLdcI4(first, out var value))
        return value;
    if (ins.Count == 2 && first.OpCode == OpCodes.Call && first.Operand is MethodReference callee
        && callee.Resolve() is { IsStatic: true, HasParameters: false } target)
        return EvalConstInt(target, depth + 1);
    // Debug builds: ldc; stloc.0; br; ldloc.0; ret
    if (ins.Count == 5 && TryLdcI4(first, out value) && ins[1].OpCode.Code.ToString().StartsWith("Stloc"))
        return value;
    return null;
}

static bool TryLdcI4(Instruction i, out int value)
{
    value = 0;
    switch (i.OpCode.Code)
    {
        case Code.Ldc_I4_M1: value = -1; return true;
        case Code.Ldc_I4_0: value = 0; return true;
        case Code.Ldc_I4_1: value = 1; return true;
        case Code.Ldc_I4_2: value = 2; return true;
        case Code.Ldc_I4_3: value = 3; return true;
        case Code.Ldc_I4_4: value = 4; return true;
        case Code.Ldc_I4_5: value = 5; return true;
        case Code.Ldc_I4_6: value = 6; return true;
        case Code.Ldc_I4_7: value = 7; return true;
        case Code.Ldc_I4_8: value = 8; return true;
        case Code.Ldc_I4_S: value = (sbyte)i.Operand; return true;
        case Code.Ldc_I4: value = (int)i.Operand; return true;
        default: return false;
    }
}

static List<string> BaseChain(TypeDefinition type)
{
    var chain = new List<string>();
    for (var t = type.BaseType; t != null; t = t.Resolve()?.BaseType)
        chain.Add(t.FullName);
    return chain;
}

// The most derived class declaring Visit(IVisitor, ISerializable, int), if not SerialComponent.
static string? FindVisitDeclaringType(TypeDefinition type)
{
    for (var t = type; t != null; t = t.BaseType?.Resolve())
    {
        if (t.FullName == "SerialComponent")
            return null;
        if (t.Methods.Any(m => m.Name == "Visit" && m.Parameters.Count == 3
                && m.Parameters[0].ParameterType.FullName == "IVisitor"
                && m.Parameters[2].ParameterType.FullName == "System.Int32"))
            return t.FullName;
    }
    return null;
}

// Mirrors Type.GetFields(Instance | Public) on Mono: most derived class first, each in
// declaration order.
static IEnumerable<FieldDefinition> PublicInstanceFields(TypeDefinition type)
{
    for (var t = type; t != null; t = t.BaseType?.Resolve())
    {
        if (t.Module != type.Module)
            yield break;
        foreach (var f in t.Fields.Where(f => f.IsPublic && !f.IsStatic))
            yield return f;
    }
}

// Resource.GetProperSerialName
static string ProperSerialName(string name) =>
    (char.ToUpperInvariant(name[0]) + name[1..]).Trim('_');

static string ScreamingSnake(string name)
{
    var s = name.Trim('_');
    var sb = new StringBuilder();
    for (var i = 0; i < s.Length; i++)
    {
        var c = s[i];
        if (i > 0 && char.IsUpper(c) && (char.IsLower(s[i - 1]) || char.IsDigit(s[i - 1])
                || (i + 1 < s.Length && char.IsLower(s[i + 1]) && char.IsUpper(s[i - 1]))))
            sb.Append('_');
        sb.Append(char.ToUpperInvariant(c));
    }
    return sb.ToString();
}
